function [body,info] = llm_request(b,best,lower,o,feedback)
%LLM_REQUEST Build a credential-free request without network I/O.
if nargin < 5, feedback=struct(); end
started=tic;
info=struct('status','FAILED','message','','accepted',0,'format_valid',0, ...
    'feasible',NaN,'context_seconds',0,'parse_seconds',0,'http_seconds',0);
context=struct('hours',b.times,'unit_count',b.d.n_units,'current_lower_bound',lower, ...
    'current_cost',best.cost,'u',best.point(b.u),'v',best.point(b.v),'w',best.point(b.w), ...
    'pmin',b.d.pmin,'pmax',b.d.pmax,'pstart',b.d.pstart,'pshut',b.d.pshut, ...
    'min_up',b.d.min_up,'min_down',b.d.min_down,'ramp_up',b.d.ramp_up,'ramp_down',b.d.ramp_down, ...
    'priced_binary_cost',b.obj(b.binary),'scenario_loads',[]);
context.original_binary_cost=b.original_obj(b.binary);
context.lagrangian_binary_price=b.obj(b.binary)-b.original_obj(b.binary);
context.priced_continuous_cost=b.obj(b.continuous);
context.quadratic_cost=b.q(b.continuous); context.block_constant=b.constant;
context.fuel_a=b.d.cost_a; context.fuel_b=b.d.cost_b;
context.fixed_cost=b.d.cost_c; context.startup_cost=b.d.startup_cost;
context.shutdown_cost=b.d.shutdown_cost; context.reserve_fraction=b.d.reserve_fraction;
context.initial_on=b.d.initial_on; context.initial_duration=b.d.initial_duration;
context.initial_output=b.d.initial_output;
context.scenario_probability=[b.scenarios.probability];
N=b.d.n_units*b.d.horizon; S=numel(b.scenarios);
ids=reshape(1:N,b.d.n_units,b.d.horizon); ids=ids(:,b.times);
for k=1:S
    context.scenario_loads(k,:)=b.scenarios(k).load(b.times);
    [~,p]=ismember(3*N+(k-1)*N+ids,b.cols);
    [~,r]=ismember(3*N+S*N+(k-1)*N+ids,b.cols);
    context.dispatch(k).p=best.point(p); context.dispatch(k).r=best.point(r);
end
context.scenario_reserve=b.d.reserve_fraction*context.scenario_loads;
% Sparse triplets retain all local rows without a dense prompt matrix.
[row,col,value]=find(b.A);
context.local_constraints=struct('triplets',[row col value],'rhs',b.rhs, ...
    'equality',b.eq,'lb',b.lb,'ub',b.ub,'binary',b.binary, ...
    'continuous',b.continuous,'u',b.u,'v',b.v,'w',b.w, ...
    'global_columns',b.cols,'one_based_indices',true);
context.current_point=best.point;
context.continuous_indices=b.continuous;
context.cut_definition='optimality: recourse >= alpha + beta''*binary; feasibility: alpha + beta''*binary <= 0';
context.cuts=best.cut;
if isfield(feedback,'cuts'), context.cuts=feedback.cuts; end
context.recent_candidates=[];
if isfield(feedback,'recent'), context.recent_candidates=feedback.recent; end
system=['Propose up to 3 alternative binary schedules to escape this stalled SA search. ' ...
    'Return ONLY JSON: {"candidates":[{"u":[...],"v":[...],"w":[...]}]}. ' ...
    'Each matrix has unit_count rows and one column per listed hour; entries must be 0 or 1. ' ...
    'u is commitment, v startup, w shutdown. Minimize the priced block objective. ' ...
    'Original cost and Lagrangian prices differ; block gains need not improve full-day cost. ' ...
    'Propose coordinated changes across units and hours, including distinct feasible escape points. ' ...
    'Cut slopes are local recourse sensitivities and lower bounds, not guaranteed savings. ' ...
    'Triplets encode A*x <= rhs except equality rows; indices refer to the local point vector. ' ...
    'Only listed local constraints are hard here; cross-block constraints are priced. ' ...
    'At a block boundary do not invent a reset to the original initial condition. ' ...
    'All proposals will be checked against the actual constraints and dispatch QP.'];
body=struct('model',o.llm_model,'instructions',system,'input',jsonencode(context), ...
    'stream',false,'store',false);
info.context_seconds=toc(started);
end
