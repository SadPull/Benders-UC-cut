"""Generate the 10-scenario IEEE118-derived instance (a project extension, not IEEE source data)."""
import argparse
import hashlib
import json
from pathlib import Path
from types import SimpleNamespace as NS

import numpy as np

from suc_benders.data import load_data
from suc_benders.validation import reachable_shortfall, transition_allowed

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT/'data'
TARGET = ROOT/'instances'/'ieee118s10'
SEED, COUNT = 20261025, 10
DAILY, DAILY_RANGE = .02, (.95, 1.03)
HOURLY, HOURLY_RANGE = .01, .02
PEAK_SHARE = .98


def sha256(content):
    return hashlib.sha256(content).hexdigest()


def dump(value):
    return (json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + '\n').encode('utf-8')


# 最大开机方案：每台机组在初始最小停机时间允许的最早小时开机并一直开到日末；不能开机的机组保持停机。
def max_commitment(d):
    start, _ = transition_allowed(d)
    u = np.ones((d.n_units, d.horizon))
    for i in range(d.n_units):
        if not d.initial_on[i]:
            u[i, :max(0, int(d.min_down[i]-d.initial_duration[i])) if start[i] else d.horizon] = 0
    return u


# 日系数整体平移基准负荷，再叠加逐小时扰动；超出容量余量或最大开机下不可达的场景整条重抽。
def generate():
    d, _ = load_data(SOURCE/'units.json', SOURCE/'stochastic.json')
    rng = np.random.default_rng(SEED)
    u, peak = max_commitment(d), PEAK_SHARE*d.pmax.sum()
    scenarios, factors, redraws = [], [], 0
    while len(scenarios) < COUNT:
        factor = float(np.clip(1 + DAILY*rng.standard_normal(), *DAILY_RANGE))
        noise = np.clip(HOURLY*rng.standard_normal(d.horizon), -HOURLY_RANGE, HOURLY_RANGE)
        load = np.round(d.base_load*factor*(1 + noise), 2)
        if load.max() > peak or reachable_shortfall(d, [NS(load=load)], u):
            redraws += 1
            continue
        factors.append(round(factor, 6))
        scenarios.append(dict(name=f's{len(scenarios)+1:02d}', probability=1/COUNT, load=[float(v) for v in load]))
    return dict(reserve_fraction=0.0, scenarios=scenarios), factors, redraws


def files():
    units = (SOURCE/'units.json').read_bytes()
    stochastic, factors, redraws = generate()
    content = {'units.json': units, 'stochastic.json': dump(stochastic)}
    provenance = dict(
        name='IEEE118-derived 54 units x 24 hours x 10 scenarios',
        scope='Project extension of data/ for stochastic experiments. Units are copied byte for byte from '
              'data/units.json; scenario loads are generated by this script and are not IEEE source data.',
        generator=dict(script='make_ieee118_scenarios.py',
                       # 按 LF 换行计算，使 Windows 检出（CRLF）后仍可校验。
                       script_sha256=sha256((ROOT/'make_ieee118_scenarios.py').read_bytes().replace(b'\r\n', b'\n')),
                       script_hash_format='SHA256 of the script with LF line endings',
                       rng='numpy.random.default_rng', seed=SEED),
        scenario_model=f'load_st = round(base_load_t * f_s * (1 + e_st), 2); f_s = clip(1 + {DAILY} z, '
                       f'{DAILY_RANGE[0]}, {DAILY_RANGE[1]}); e_st = clip({HOURLY} z, -{HOURLY_RANGE}, '
                       f'{HOURLY_RANGE}); z standard normal; {COUNT} equiprobable scenarios',
        acceptance=f'peak load <= {PEAK_SHARE} * sum(pmax) and no reachable-output shortfall when every unit '
                   'is on from the earliest hour its initial minimum down time allows; otherwise redraw',
        redraws=redraws, daily_factors=factors,
        model_choices=['reserve_fraction 0, as in data/stochastic.json',
                       'shift range narrowed from the +-30% of Mahroo & Kargarian (TPWRS 2026): the fleet '
                       'has 7.5% headroom over the base peak and hour 1 is ramp limited'],
        input_sha256={name: sha256(value) for name, value in content.items()})
    return {**content, 'provenance.json': dump(provenance)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated files without writing')
    check = parser.parse_args().check
    for name, content in files().items():
        path = TARGET/name
        if check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit(f'{path} differs from the generator output')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print('checked' if check else f'wrote {TARGET}')


if __name__ == '__main__':
    main()
